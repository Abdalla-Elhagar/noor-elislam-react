export function getProductCartId(product) {
  return `product-${product.id}-${product.name.trim()}`;
}

export function getProductPricing(product) {
  const price = product.price;
  const numericPrice = Number(price);

  if (price === null || price === undefined || !Number.isFinite(numericPrice)) {
    return { price, oldPrice: undefined };
  }

  const numericOldPrice = Number(product.oldPrice);
  if (
    product.oldPrice !== null &&
    product.oldPrice !== undefined &&
    Number.isFinite(numericOldPrice) &&
    numericOldPrice > numericPrice
  ) {
    return { price: numericPrice, oldPrice: numericOldPrice };
  }

  const discount = Number(product.discount);
  if (discount > 0 && discount < 100) {
    return {
      price: Math.round(numericPrice * (1 - discount / 100)),
      oldPrice: numericPrice,
    };
  }

  return { price: numericPrice, oldPrice: undefined };
}

